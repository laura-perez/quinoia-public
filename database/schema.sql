CREATE TABLE public.menuResult (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  submissionId uuid NOT NULL,
  userId uuid NOT NULL,
  resultBundle jsonb NOT NULL,
  numRecipes integer NOT NULL,
  numServings integer NOT NULL,
  shareId text UNIQUE,
  shareActive boolean NOT NULL DEFAULT true,
  shareCreatedAt timestamp with time zone NOT NULL DEFAULT now(),
  createdAt timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT menuResult_pkey PRIMARY KEY (id),
  CONSTRAINT menuResult_userId_fkey FOREIGN KEY (userId) REFERENCES public.user(id),
  CONSTRAINT menuResult_submissionId_fkey FOREIGN KEY (submissionId) REFERENCES public.submission(id)
);
CREATE TABLE public.runLog (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  submissionId uuid,
  menuResultId uuid,
  runId text,
  node text NOT NULL,
  inputJson jsonb,
  outputJson jsonb,
  tokensIn integer,
  tokensOut integer,
  costEstimateEur numeric,
  status text NOT NULL DEFAULT 'ok'::text,
  startedAt timestamp with time zone NOT NULL DEFAULT now(),
  endedAt timestamp with time zone,
  CONSTRAINT runLog_pkey PRIMARY KEY (id),
  CONSTRAINT runLog_menuResultId_fkey FOREIGN KEY (menuResultId) REFERENCES public.menuResult(id),
  CONSTRAINT runLog_submissionId_fkey FOREIGN KEY (submissionId) REFERENCES public.submission(id)
);
CREATE TABLE public.submission (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  userId uuid NOT NULL,
  rawFormJson jsonb NOT NULL,
  normalizedInput jsonb NOT NULL,
  age integer CHECK (age >= 16 AND age <= 100),
  gender USER-DEFINED,
  heightCm integer CHECK ("heightCm" >= 100 AND "heightCm" <= 250),
  weightKg numeric CHECK ("weightKg" >= 40::numeric AND "weightKg" <= 150::numeric),
  diet USER-DEFINED,
  proteinPreferences ARRAY NOT NULL DEFAULT '{}'::text[] CHECK ("proteinPreferences" <@ ARRAY['Beef'::text, 'Poultry'::text, 'Fish'::text, 'Eggs'::text, 'Dairy'::text, 'Tofu'::text, 'Legumes'::text, 'Meat alternatives'::text]),
  equipmentAvailable ARRAY NOT NULL DEFAULT '{}'::text[] CHECK ("equipmentAvailable" <@ ARRAY['Oven'::text, 'Blender'::text, 'Thermomix'::text, 'Air Fryer'::text]),
  numRecipes integer CHECK ("numRecipes" >= 2 AND "numRecipes" <= 7),
  numServings integer CHECK ("numServings" >= 1 AND "numServings" <= 4),
  dislikedFoods text,
  favoriteFoods text,
  cookingLevel USER-DEFINED,
  freeTextMessage text,
  locale text NOT NULL DEFAULT 'fr-FR'::text,
  unitSystem text NOT NULL DEFAULT 'metric'::text,
  consent boolean NOT NULL DEFAULT true,
  consentedAt timestamp with time zone NOT NULL,
  consentVersion text NOT NULL DEFAULT 'v1'::text,
  recaptchaScore numeric,
  recaptchaSuccess boolean,
  recaptchaHostname text,
  recaptchaAction text,
  recaptchaChallengeTs timestamp with time zone,
  ipAddress inet,
  userAgent text,
  runId text,
  status text NOT NULL DEFAULT 'pending'::text,
  createdAt timestamp with time zone NOT NULL DEFAULT now(),
  activityDeskJob boolean,
  activityDailySteps text CHECK ("activityDailySteps" = ANY (ARRAY['<5k'::text, '5-8k'::text, '>8k'::text])),
  activitySessionsPerWeek text CHECK ("activitySessionsPerWeek" = ANY (ARRAY['0'::text, '1-2'::text, '3-4'::text, '>=5'::text])),
  activityHighIntensity boolean,
  CONSTRAINT submission_pkey PRIMARY KEY (id),
  CONSTRAINT submission_userId_fkey FOREIGN KEY (userId) REFERENCES public.user(id)
);
CREATE TABLE public.user (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  email text NOT NULL UNIQUE,
  firstName text,
  createdAt timestamp with time zone NOT NULL DEFAULT now(),
  lastSubmissionAt timestamp with time zone,
  lastMenuResultId uuid,
  CONSTRAINT user_pkey PRIMARY KEY (id)
);